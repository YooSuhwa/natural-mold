"""Read delivery receipts from the running child graph's own checkpoint namespace."""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any
from uuid import UUID, uuid5

from langchain_core.messages import AIMessage, HumanMessage
from langchain_core.runnables import RunnableConfig
from langgraph.channels.delta import DeltaChannel
from langgraph.checkpoint.base import BaseCheckpointSaver, CheckpointTuple
from langgraph.config import get_config
from langgraph.constants import CONFIG_KEY_CHECKPOINTER
from langgraph.graph.message import _messages_delta_reducer

from app.authz.org_context import OrgContext
from app.tenancy.checkpoint_audit import CHECKPOINT_TENANT_KEY


def child_instruction_message_id(instruction_id: UUID) -> str:
    return str(uuid5(instruction_id, "moldy.chat.child-instruction.message.v1"))


async def _checkpoint_messages(
    saver: BaseCheckpointSaver[Any], saved: CheckpointTuple
) -> Sequence[Any]:
    # Match the pinned DeepAgentState reducer. Reading only ancestor writes would
    # count a message later removed by a fork overwrite or summary; consulting
    # pending writes of this checkpoint could instead count an uncommitted step.
    reducer = DeltaChannel(lambda base, writes: _messages_delta_reducer(base, list(writes)))
    direct = saved.checkpoint["channel_values"].get("messages")
    if direct is not None:
        return reducer.from_checkpoint(direct).get()
    histories = await saver.aget_delta_channel_history(config=saved.config, channels=["messages"])
    history = histories.get("messages")
    if history is None:
        return ()
    channel = reducer.from_checkpoint(history.get("seed"))
    channel.replay_writes(history["writes"])
    return channel.get()


async def saved_child_step(
    context: OrgContext,
    conversation_id: UUID,
    run_id: UUID,
    tool_call_id: str,
    checkpoint_ns: str,
    *,
    child_id: UUID,
    messages_by_id: Mapping[UUID, str],
    config: RunnableConfig | None = None,
) -> tuple[str, set[UUID]] | None:
    """Prove a checkpoint belongs to this child, then identify answered instructions.

    ``config`` must be the active graph configuration captured at task dispatch or
    in its child hook. A prepared run thereby uses its frozen lease saver; no
    lookup opens a process-wide saver. The caller has already authorized the
    conversation, current run and particular child before requesting proof.
    """
    if not checkpoint_ns or not tool_call_id:
        return None
    if config is None:
        try:
            config = get_config()
        except RuntimeError:  # outside the graph; no saver authority
            return None
    runtime = config.get("configurable", {})
    active_ns = runtime.get("checkpoint_ns")
    expected = {
        "thread_id": str(conversation_id),
        "moldy_run_id": str(run_id),
        CHECKPOINT_TENANT_KEY: str(context.tenant_id),
    }
    if any(runtime.get(key) != value for key, value in expected.items()):
        return None
    if not isinstance(active_ns, str) or not (
        active_ns == checkpoint_ns or active_ns.rpartition("|")[0] == checkpoint_ns
    ):
        return None
    saver = runtime.get(CONFIG_KEY_CHECKPOINTER)
    if not isinstance(saver, BaseCheckpointSaver):
        return None
    saved = await saver.aget_tuple({"configurable": {**expected, "checkpoint_ns": checkpoint_ns}})
    if saved is None:
        return None
    stored = saved.config.get("configurable", {})
    checkpoint_id = stored.get("checkpoint_id")
    if (
        not isinstance(checkpoint_id, str)
        or not checkpoint_id
        or checkpoint_id != saved.checkpoint["id"]
        or stored.get("thread_id") != str(conversation_id)
        or stored.get("checkpoint_ns") != checkpoint_ns
        or saved.metadata.get(CHECKPOINT_TENANT_KEY) != expected[CHECKPOINT_TENANT_KEY]
        or saved.metadata.get("moldy_run_id") != expected["moldy_run_id"]
        or saved.metadata.get("lc_subagent_tool_call_id") != tool_call_id
    ):
        return None

    marker = saved.checkpoint["channel_values"].get("moldy_child_model_receipts")
    if (
        not messages_by_id
        or not isinstance(marker, Mapping)
        or (marker.get("child"), marker.get("run"), marker.get("tool"))
        != (str(child_id), str(run_id), tool_call_id)
    ):
        return checkpoint_id, set()
    outputs = marker.get("outputs")
    if not isinstance(outputs, Mapping) or not outputs:
        return checkpoint_id, set()

    # A later assistant message can also be a refusal generated by middleware.
    # Only the trusted model boundary can bind its actual output ID to the
    # instructions which reached that call. The committed history must agree.
    candidates = {child_instruction_message_id(key): key for key in messages_by_id}
    seen_by_model: set[str] = set()
    confirmed: set[UUID] = set()
    for msg in reversed(await _checkpoint_messages(saver, saved)):
        if isinstance(msg, AIMessage):
            receipts = outputs.get(msg.id)
            if isinstance(receipts, list):
                seen_by_model.update(item for item in receipts if isinstance(item, str))
        elif isinstance(msg, HumanMessage) and msg.id in candidates:
            key = candidates[msg.id]
            if str(key) in seen_by_model and msg.content == messages_by_id[key]:
                confirmed.add(key)
    return checkpoint_id, confirmed
